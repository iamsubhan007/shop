// Writes the fonts of the menu PDF into a JavaScript module (src/lib/menuPdf/fonts.generated.js), so the PDF looks the
// same everywhere: a serverless Chromium has no useful system fonts, and files read at run time are easy to lose in a
// deployment. Roboto (Apache-2.0 / OFL) is what Android visitors of the website see; Noto Naskh Arabic (OFL) covers
// Urdu names. Run after changing fonts:  node scripts/make-menu-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';

const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const LATIN_EXT = 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF';
const ARABIC = 'U+0600-06FF,U+0750-077F,U+0870-089F,U+08A0-08FF,U+200C-200E,U+FB50-FDFF,U+FE70-FEFC';

const faces = [];
const add = (family, weight, range, file) => {
  const data = fs.readFileSync(path.join('node_modules', '@fontsource', file)).toString('base64');
  faces.push(`@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};src:url(data:font/woff2;base64,${data}) format('woff2');unicode-range:${range};}`);
};

for (const weight of [400, 500, 700, 900]) {
  add('MenuSans', weight, LATIN, `roboto/files/roboto-latin-${weight}-normal.woff2`);
  add('MenuSans', weight, LATIN_EXT, `roboto/files/roboto-latin-ext-${weight}-normal.woff2`);
}
for (const weight of [400, 700]) add('MenuUrdu', weight, ARABIC, `noto-naskh-arabic/files/noto-naskh-arabic-arabic-${weight}-normal.woff2`);

const out = path.join('src', 'lib', 'menuPdf', 'fonts.generated.js');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `// Generated by scripts/make-menu-fonts.mjs. Do not edit.\n// Roboto (c) Google, Apache-2.0 / OFL-1.1. Noto Naskh Arabic (c) Google, OFL-1.1.\nexport const FONT_CSS = ${JSON.stringify(faces.join('\n'))};\n`,
);
console.log('wrote', out, `${Math.round(fs.statSync(out).size / 1024)} KB`);
